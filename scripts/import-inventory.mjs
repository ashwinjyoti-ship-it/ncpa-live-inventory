// Converts your inventory Excel sheet into a SQL file that can be loaded
// into Cloudflare D1 with `wrangler d1 execute`.
//
// Usage:
//   node scripts/import-inventory.mjs [path-to-xlsx]
//   (defaults to ./inventory.xlsx in the project root)
//
// Then load it into D1:
//   wrangler d1 execute DB --local  --file=./d1/seed.sql   (local dev DB)
//   wrangler d1 execute DB --remote --file=./d1/seed.sql   (production DB)
//
// Or just run: npm run db:import:local / npm run db:import:remote
//
// Expected sheet columns (header names are matched case-insensitively,
// order doesn't matter):
//   Venue    - venue name, e.g. "JBT"
//   Category - category/group name, e.g. "MAIN PA SPEAKERS"
//   Item     - item name, e.g. "MEYER 900 SUB"
//   Qty      - quantity, e.g. 6
//
// One row per item. Category order is preserved based on first appearance
// per venue (matches how the app orders categories via `position`).
//
// If your sheet uses different column names, edit COLUMN_ALIASES below.

import { readFileSync, writeFileSync, existsSync } from 'fs'
import { fileURLToPath } from 'url'
import path from 'path'
import xlsx from 'xlsx'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(__dirname, '..')

const inputPath = process.argv[2]
  ? path.resolve(process.cwd(), process.argv[2])
  : path.join(projectRoot, 'inventory.xlsx')

const outputPath = path.join(projectRoot, 'd1', 'seed.sql')

const COLUMN_ALIASES = {
  venue: ['venue', 'venue name', 'location'],
  category: ['category', 'group', 'category name'],
  item: ['item', 'item name', 'equipment', 'name'],
  qty: ['qty', 'quantity', 'count'],
}

function findKey(row, aliases) {
  const keys = Object.keys(row)
  for (const alias of aliases) {
    const match = keys.find((k) => k.trim().toLowerCase() === alias)
    if (match) return match
  }
  return null
}

function sqlEscape(value) {
  return String(value).replace(/'/g, "''")
}

function uuid() {
  return crypto.randomUUID()
}

function main() {
  if (!existsSync(inputPath)) {
    console.error(`\n✗ Excel file not found: ${inputPath}`)
    console.error(`  Drop your inventory sheet at ./inventory.xlsx, or pass a path:`)
    console.error(`  node scripts/import-inventory.mjs path/to/sheet.xlsx\n`)
    process.exit(1)
  }

  const workbook = xlsx.readFile(inputPath)
  const sheetName = workbook.SheetNames[0]
  const sheet = workbook.Sheets[sheetName]
  const rows = xlsx.utils.sheet_to_json(sheet, { defval: '' })

  if (rows.length === 0) {
    console.error('✗ No rows found in the first sheet.')
    process.exit(1)
  }

  const sample = rows[0]
  const venueKey = findKey(sample, COLUMN_ALIASES.venue)
  const categoryKey = findKey(sample, COLUMN_ALIASES.category)
  const itemKey = findKey(sample, COLUMN_ALIASES.item)
  const qtyKey = findKey(sample, COLUMN_ALIASES.qty)

  if (!venueKey || !categoryKey || !itemKey) {
    console.error('✗ Could not find Venue / Category / Item columns.')
    console.error(`  Found columns: ${Object.keys(sample).join(', ')}`)
    console.error(`  Update COLUMN_ALIASES in scripts/import-inventory.mjs to match your headers.`)
    process.exit(1)
  }

  const venues = new Map() // name -> id
  const categories = new Map() // `${venueId}::${name}` -> { id, position }
  const items = []

  let skipped = 0

  for (const row of rows) {
    const venueName = String(row[venueKey] || '').trim().toUpperCase()
    const categoryName = String(row[categoryKey] || '').trim().toUpperCase()
    const itemName = String(row[itemKey] || '').trim().toUpperCase()
    const qty = qtyKey ? parseInt(row[qtyKey], 10) || 0 : 0

    if (!venueName || !categoryName || !itemName) {
      skipped++
      continue
    }

    if (!venues.has(venueName)) {
      venues.set(venueName, uuid())
    }
    const venueId = venues.get(venueName)

    const catKey = `${venueId}::${categoryName}`
    if (!categories.has(catKey)) {
      const position = [...categories.keys()].filter((k) => k.startsWith(`${venueId}::`)).length
      categories.set(catKey, { id: uuid(), name: categoryName, venueId, position })
    }
    const category = categories.get(catKey)

    items.push({ id: uuid(), name: itemName, qty, categoryId: category.id })
  }

  const lines = []
  lines.push('-- Generated by scripts/import-inventory.mjs — do not edit by hand.')
  lines.push('-- Re-run the script to regenerate after changing the source spreadsheet.')
  lines.push('')
  lines.push('DELETE FROM items;')
  lines.push('DELETE FROM categories;')
  lines.push('DELETE FROM venues;')
  lines.push('')

  for (const [name, id] of venues) {
    lines.push(`INSERT INTO venues (id, name) VALUES ('${id}', '${sqlEscape(name)}');`)
  }
  lines.push('')

  for (const { id, name, venueId, position } of categories.values()) {
    lines.push(
      `INSERT INTO categories (id, name, venue_id, position) VALUES ('${id}', '${sqlEscape(name)}', '${venueId}', ${position});`
    )
  }
  lines.push('')

  for (const { id, name, qty, categoryId } of items) {
    lines.push(
      `INSERT INTO items (id, name, qty, category_id) VALUES ('${id}', '${sqlEscape(name)}', ${qty}, '${categoryId}');`
    )
  }
  lines.push('')

  writeFileSync(outputPath, lines.join('\n'), 'utf8')

  console.log(`✓ Parsed ${items.length} items across ${categories.size} categories and ${venues.size} venues.`)
  if (skipped) console.log(`  (skipped ${skipped} rows missing venue/category/item)`)
  console.log(`✓ Wrote ${path.relative(projectRoot, outputPath)}`)
  console.log('')
  console.log('Next: load it into D1 with one of:')
  console.log('  npm run db:import:local    # local dev database')
  console.log('  npm run db:import:remote   # production database')
}

main()
